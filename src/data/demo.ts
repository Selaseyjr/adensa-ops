/**
 * Every demo date is relative to the day the app is opened, so the demo never
 * goes stale: day(0) is today, day(-3) three days ago, day(5) five days ahead.
 * The seed was authored with "today" = 14 Oct 2026; offsets keep that shape.
 */
function day(offset: number, from: Date = new Date()): string {
  const d = new Date(from.getFullYear(), from.getMonth(), from.getDate() + offset)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}

